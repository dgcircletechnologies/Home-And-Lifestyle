/* global FormData, Blob */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');

test('isolated media CRUD and public video showcase', { skip: !process.env.TEST_DATABASE_URL }, async t => {
  const database = new URL(process.env.TEST_DATABASE_URL);
  assert.match(database.pathname, /^\/media_test_/);
  process.env.DATABASE_URL = process.env.TEST_DATABASE_URL;
  process.env.CORS_ORIGINS = 'http://localhost:3100';
  process.env.FRONTEND_URL = 'http://localhost:3100';
  const { createApp } = require('../dist/src/bootstrap.js');
  const { AuthService } = require('../dist/src/auth/auth.service.js');
  const { CategoryImageService } = require('../dist/src/categories/category-image.service.js');
  const { ProductVideoService } = require('../dist/src/products/product-video.service.js');
  const app = await createApp();
  await app.listen(0, '127.0.0.1');
  t.after(() => app.close());
  app.get(AuthService).resolve = async () => ({ id: randomUUID(), name: 'Admin', email: 'admin@example.test', role: 'ADMIN' });
  let imageNumber = 0;
  app.get(CategoryImageService).upload = async () => ({ url: `https://example.test/image-${++imageNumber}.png`, publicId: `test/image-${imageNumber}`, format: 'png', width: 1, height: 1, resourceType: 'image' });
  app.get(CategoryImageService).remove = async () => {};
  app.get(ProductVideoService).upload = async () => ({ url: 'https://example.test/video.webm', publicId: 'test/video' });
  app.get(ProductVideoService).remove = async () => {};
  const base = await app.getUrl();
  const call = async (path, method = 'GET', body) => { const response = await fetch(`${base}/api/${path}`, { method, headers: { Origin: 'http://localhost:3100', 'X-CSRF-Protection': '1', Authorization: 'Bearer test', ...(body && !(body instanceof FormData) ? { 'Content-Type': 'application/json' } : {}) }, body: body instanceof FormData ? body : body === undefined ? undefined : JSON.stringify(body) }); return { status: response.status, body: await response.json() }; };
  const form = (payload, count) => { const value = new FormData(); value.set('payload', JSON.stringify(payload)); for (let index = 0; index < count; index++) value.append('images', new Blob(['image'], { type: 'image/png' }), `image-${index}.png`); return value; };
  const categoryPayload = { name: 'Decor', slug: `decor-${randomUUID().slice(0, 8)}` };
  assert.equal((await call('admin/categories', 'POST', categoryPayload)).status, 400);
  const category = await call('admin/categories/with-images', 'POST', form(categoryPayload, 2));
  assert.equal(category.status, 201, JSON.stringify(category.body));
  assert.equal(category.body.image.url, 'https://example.test/image-1.png');
  assert.equal(category.body.secondaryImage.url, 'https://example.test/image-2.png');
  const productPayload = { name: 'Video Vase', slug: `video-vase-${randomUUID().slice(0, 8)}`, description: 'A vase.', categoryIds: [category.body.id], variants: [{ sku: `SKU-${randomUUID()}`, pricePaise: 90000, stockQuantity: 2 }] };
  assert.equal((await call('admin/products', 'POST', productPayload)).status, 400);
  const product = await call('admin/products/with-images', 'POST', form(productPayload, 2));
  assert.equal(product.status, 201, JSON.stringify(product.body));
  assert.equal(product.body.images.length, 2);
  const third = new FormData(); third.set('image', new Blob(['image'], { type: 'image/png' }), 'third.png');
  assert.equal((await call(`admin/products/${product.body.id}/images`, 'POST', third)).status, 400);
  const video = new FormData(); video.set('video', new Blob(['video'], { type: 'video/webm' }), 'clip.webm');
  assert.equal((await call(`admin/products/${product.body.id}/video`, 'POST', video)).status, 201);
  assert.equal((await call(`admin/products/${product.body.id}`, 'PATCH', { showInHomeVideoShowcase: true })).status, 200);
  assert.equal((await call(`admin/products/${product.body.id}/status`, 'PATCH', { status: 'PUBLISHED' })).status, 200);
  const publicHome = await call('storefront/home');
  assert.equal(publicHome.status, 200, JSON.stringify(publicHome.body));
  assert.equal(publicHome.body.videoProducts.length, 1);
  assert.equal((await call(`admin/products/${product.body.id}/status`, 'PATCH', { status: 'DRAFT' })).status, 200);
  assert.equal((await call('storefront/home')).body.videoProducts.length, 0);
  assert.equal((await call(`admin/products/${product.body.id}/status`, 'PATCH', { status: 'PUBLISHED' })).status, 200);
  const detail = await call(`storefront/products/${productPayload.slug}`);
  assert.equal(detail.body.images.length, 2);
  assert.equal(detail.body.videoUrl, 'https://example.test/video.webm');
  assert.equal((await call(`admin/products/${product.body.id}/video`, 'DELETE')).status, 200);
  assert.equal((await call('storefront/home')).body.videoProducts.length, 0);
});
